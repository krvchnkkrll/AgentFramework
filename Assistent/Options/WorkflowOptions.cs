namespace Assistant.Options;

/// <summary>
/// Стенд «подготовь документ»: три агента, два внешних сервиса-заглушки, замер времени.
/// Секция Assistant:Workflow.
/// </summary>
public sealed class WorkflowOptions
{
    /// <summary>
    /// Задержка ответа сервисов-заглушек (оргструктура, ЭДО), в секундах. Именно она изображает
    /// реальное обращение к внешнему API — без неё распараллеливать нечего и мерить нечего.
    /// </summary>
    public int ApiDelaySeconds { get; init; } = 5;

    /// <summary>
    /// Потолок ответа подагентов. Их задача — вернуть найденное, а не рассуждать,
    /// поэтому потолок нарочно низкий: каждый лишний токен это лишние секунды на локальной модели.
    /// </summary>
    public int SubAgentMaxOutputTokens { get; init; } = 512;

    /// <summary>Потолок ответа агента-составителя. Он единственный пишет длинный текст.</summary>
    public int ComposerMaxOutputTokens { get; init; } = 2048;

    /// <summary>Температура всех трёх агентов стенда. Низкая — чтобы прогоны были сравнимы между собой.</summary>
    public float Temperature { get; init; } = 0.2f;

    /// <summary>
    /// Выполнять ли инструменты, выданные моделью за один ход, одновременно. Влияет только
    /// на режим AgentTools.
    ///
    /// Умолчание фреймворка — false: FunctionInvokingChatClient вызывает инструменты по очереди,
    /// даже когда модель попросила оба сразу. На нашем сценарии это ровно плюс одна задержка
    /// внешнего сервиса. Выключите флаг, чтобы увидеть разницу своими глазами.
    /// </summary>
    public bool AllowConcurrentToolCalls { get; init; } = true;
}
