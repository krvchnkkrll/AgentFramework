namespace Assistant.Contracts.Skills;

/// <summary>
/// Откуда слой ассистента берёт архив скилла.
///
/// Нужен, чтобы ассистент не знал ни про базу, ни про файловое хранилище: ему достаточно
/// идентификатора файла, а чем этот идентификатор разрешается — папкой на диске, S3 или
/// чем угодно ещё — решает приложение.
/// </summary>
public interface ISkillPackageSource
{
    /// <summary>
    /// Открывает архив на чтение. null — файла в хранилище нет: скилл заведён в базе,
    /// а содержимое потерялось. Это не исключение, а нормальная ситуация, которую агент
    /// переживает, просто оставшись без этого скилла.
    /// </summary>
    Task<Stream?> OpenAsync(Guid fileId, CancellationToken cancellationToken = default);
}
